def S(bundle, comment, en, zh, es, ja, pt, de, fr, ko, ru, hant):
    return {"bundle": bundle, "comment": comment, "values": V(en, zh, es, ja, pt, de, fr, ko, ru, hant)}


def P(bundle, comment, forms):
    # forms[lang] is (one, other) or (one, few, many, other) or a single string used for every needed category.
    normalized = {}
    for lang, form in forms.items():
        if isinstance(form, str):
            normalized[lang] = {"other": form} if lang in ("ja", "ko", "zh-Hans", "zh-Hant") else {
                "one": form, "other": form
            }
            if lang == "ru":
                normalized[lang] = {"one": form, "few": form, "many": form, "other": form}
        elif len(form) == 2:
            one, other = form
            if lang == "ru":
                normalized[lang] = {"one": one, "few": other, "many": other, "other": other}
            elif lang in ("ja", "ko", "zh-Hans", "zh-Hant"):
                normalized[lang] = {"other": other}
            else:
                normalized[lang] = {"one": one, "other": other}
        else:
            one, few, many, other = form
            normalized[lang] = {"one": one, "few": few, "many": many, "other": other}
    return {"bundle": bundle, "comment": comment, "plural": True, "forms": normalized}


